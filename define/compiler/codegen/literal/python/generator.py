"""Python literal code generator for the Define compiler."""

import typing
from pathlib import Path

import jinja2

from define.compiler import ast
from define.compiler.codegen import action_plan
from define.compiler.codegen.literal.python import (
    action_context,
    action_definition,
    naming,
    position_definition,
    template_context,
    template_env,
)
from define.compiler.data_structures import typed_name_dict
from define.compiler.graphs import reference_graph
from define.compiler.validator.reference_graph import (
    operation_graph,
    operation_graph_labeler,
)

_TEMPLATES_DIR = Path(__file__).parent
_COMPILED_DIR = _TEMPLATES_DIR / "templates.compiled"
_ENV = template_env.create_environment(_TEMPLATES_DIR, _COMPILED_DIR)
typing.cast(
    "dict[str, object]",
    _ENV.globals,
).update(
    ActionRole=action_context.ActionRole,
    ChainAccessor=template_context.ChainAccessor,
    StatementKind=template_context.StatementKind,
)
_POSITION_TEMPLATE = _ENV.get_template("position_definition.j2")
_ACTION_TEMPLATE = _ENV.get_template("action_definition.j2")
_ENTRY_POINT_TEMPLATE = _ENV.get_template("entry_point.j2")
_PACKAGE_INIT = '"""Generated by the Define compiler."""\n'


class PythonLiteralCodeGenerator:
    """Generates literal Python code for a validated Define entry point."""

    def generate(
        self,
        graph: reference_graph.ReferenceGraph,
        operation_graphs: operation_graph.OperationGraphs,
        entry_point: ast.ActionDefinition,
        output_dir: Path,
        *,
        trace_operations: bool = False,
    ):
        """Generate Python files for the entry-point constructor and its references."""
        plans = action_plan.ActionPlans(operation_graphs, entry_point.typed_name)
        operation_labels = (
            operation_graph_labeler.OperationGraphLabeler(operation_graphs)
            if trace_operations
            else None
        )
        converter = naming.NameConverter()
        action_contexts: list[action_context.ActionDefinitionContext] = []
        position_contexts: list[template_context.PositionDefinitionContext] = []
        generated_actions = typed_name_dict.TypedNameDict[
            ast.GlobalTypedName, action_context.GeneratedAction
        ]()
        for definition in graph.dfs_postorder_from(entry_point):
            if isinstance(definition, ast.ActionDefinition):
                if definition.typed_name == entry_point.typed_name:
                    role = action_context.ActionRole.ENTRY_POINT
                else:
                    role = action_context.ActionRole.ACTION
                plan = plans.plan_for(definition)
                generated_action = action_definition.ActionDefinitionGenerator(
                    definition,
                    converter,
                    role,
                    generated_actions,
                    plan,
                    operation_labels,
                ).generate()
                generated_actions[definition.typed_name] = generated_action
                action_contexts.append(generated_action.context)
            elif isinstance(definition, ast.PositionDefinition):
                position_contexts.append(
                    position_definition.PositionDefinitionGenerator(
                        definition, converter
                    ).generate()
                )

        all_module_names: set[str] = set()

        for ctx in action_contexts:
            all_module_names.add(ctx.module_name)
            self._write_definition_file(_ACTION_TEMPLATE, ctx, output_dir)

        for ctx in position_contexts:
            all_module_names.add(ctx.module_name)
            self._write_definition_file(_POSITION_TEMPLATE, ctx, output_dir)

        self._write_init_files(all_module_names, output_dir)

        entry_ctx = action_contexts[-1]
        self._write_entry_point(entry_ctx, output_dir)

    def _write_definition_file(
        self,
        tmpl: jinja2.Template,
        ctx: action_context.ActionDefinitionContext
        | template_context.PositionDefinitionContext,
        output_dir: Path,
    ):
        """Render and write a definition file."""
        content = tmpl.render(definition=ctx)

        # TODO: Two definitions whose FQUN paths map to the same Python module
        # (e.g., a position and an action with the same `/path` defined in one
        # source file, or two positions sharing a path) will silently overwrite
        # each other here. The generator needs to either group same-module
        # definitions into a single rendered file or reject the collision.
        file_path = output_dir / naming.file_path_for_module(ctx.module_name)
        file_path.parent.mkdir(parents=True, exist_ok=True)
        _ = file_path.write_text(content)

    def _write_init_files(self, module_names: set[str], output_dir: Path):
        """Write empty __init__.py files for intermediate packages."""
        needed_dirs: set[Path] = set()
        for module_name in module_names:
            file_path = naming.file_path_for_module(module_name)
            for parent in file_path.parents:
                if parent == Path("."):
                    continue
                needed_dirs.add(parent)

        for dir_path in sorted(needed_dirs):
            init_file = output_dir / dir_path / "__init__.py"
            if not init_file.exists():
                _ = init_file.write_text(_PACKAGE_INIT)

    def _write_entry_point(
        self,
        entry_ctx: action_context.ActionDefinitionContext,
        output_dir: Path,
    ):
        """Write the __main__.py entry point file."""
        content = _ENTRY_POINT_TEMPLATE.render(
            entry_reference=naming.ClassReference(
                module_name=entry_ctx.module_name,
                class_name=entry_ctx.class_name,
            ),
            trace_operations=entry_ctx.trace_operations,
        )
        _ = (output_dir / "__main__.py").write_text(content)
