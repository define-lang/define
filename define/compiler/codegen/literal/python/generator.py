import threading
import typing
from pathlib import Path

import msgspec

from define.compiler import ast
from define.compiler.codegen.literal.python import (
    _templates,
    action_definition,
    encoding_operation_definition,
    naming,
    position_definition,
)
from define.compiler.graphs import reference_graph_executor

if typing.TYPE_CHECKING:
    from collections.abc import Sequence

    from define.compiler.codegen.literal.python import (
        action_context,
    )
    from define.compiler.validator import codegen_input as codegen_input_types

_PACKAGE_INIT = '"""Generated by the Define compiler."""\n'


class _ModulePart(msgspec.Struct, frozen=True):
    """One definition's rendered classes and what its module header needs."""

    definition_index: int
    body: str
    imports: list[str]
    # Names that the module imports from typing.
    typing_names: list[str]
    needs_runtime_import: bool


@typing.final
class _SharedModule:
    """Collects the parts of a module that several definitions share."""

    def __init__(self, definition_count: int):
        """Initialize with the number of definitions that share the module."""
        self._remaining = definition_count
        self._parts: list[_ModulePart] = []
        self._lock = threading.Lock()

    def add_part(self, part: _ModulePart) -> list[_ModulePart] | None:
        """Add one definition's part, returning every part once the last arrives.

        The parts are in definition order.
        """
        # Definitions sharing a module can finish on different workers at once.
        with self._lock:
            self._parts.append(part)
            self._remaining -= 1
            if self._remaining:
                return None
        # Referenced definitions come first in definition order, and a class
        # must be defined before its module's other classes refer to it.
        return sorted(self._parts, key=lambda part: part.definition_index)


def _generates_module_part(definition: ast.GlobalDefinition) -> bool:
    # Literals are already in their values' encodings in generated code, so
    # values, encodings, and Potential Literals need no code of their own.
    # Executing a Value Operation runs the Encoding Operation that performs it,
    # so Value Operations need no code either.
    return not isinstance(
        definition,
        ast.ValueDefinition
        | ast.EncodingDefinition
        | ast.PotentialLiteralDefinition
        | ast.ValueOperationDefinition,
    )


def _typing_names(*, classvar: bool, never: bool, override: bool) -> list[str]:
    typing_names: list[str] = []
    if classvar:
        typing_names.append("ClassVar")
    if never:
        typing_names.append("Never")
    if override:
        typing_names.append("override")
    return typing_names


def _module_name(
    definition: ast.GlobalDefinition, converter: naming.NameConverter
) -> str:
    """Return the name of the module that holds a definition's generated code."""
    if isinstance(definition, ast.EncodingOperationDefinition):
        return converter.function_reference(definition.typed_name).module_name
    return converter.module_name(definition.typed_name.name_content)


class _ModulePlan(msgspec.Struct, frozen=True):
    """Where each definition's classes go among the generated modules."""

    # Keyed by full typed name.
    definition_indexes: dict[str, int]
    # Definitions of different name types at the same path share a module.
    shared_modules: dict[str, _SharedModule]

    @classmethod
    def from_definitions(
        cls,
        definitions: Sequence[ast.GlobalDefinition],
        converter: naming.NameConverter,
    ) -> _ModulePlan:
        """Assign definitions to modules, in definition order."""
        definition_indexes: dict[str, int] = {}
        definition_counts: dict[str, int] = {}
        # A package must not get the name of a function in its parent package,
        # so every function name is reserved before any module is named.
        for definition in definitions:
            if isinstance(definition, ast.EncodingOperationDefinition):
                converter.reserve_function_name(definition.typed_name)
        # Authority-name and package-name collisions are assigned by first use,
        # so this runs in definition order before workers share the converter.
        for index, definition in enumerate(definitions):
            module_name = _module_name(definition, converter)
            if _generates_module_part(definition):
                definition_indexes[definition.typed_name.full_typed_name] = index
                definition_counts[module_name] = (
                    definition_counts.get(module_name, 0) + 1
                )
        shared_modules: dict[str, _SharedModule] = {}
        for module_name, count in definition_counts.items():
            if count > 1:
                shared_modules[module_name] = _SharedModule(count)
        return cls(definition_indexes=definition_indexes, shared_modules=shared_modules)


@typing.final
class _DefinitionGenerator:
    """Generate definitions after their referenced definitions complete."""

    def __init__(
        self,
        codegen_input: codegen_input_types.CodegenInput,
        entry_point: ast.ActionDefinition,
        converter: naming.NameConverter,
        module_plan: _ModulePlan,
        output_dir: Path,
        *,
        trace_operations: bool,
    ):
        """Initialize the shared generation inputs."""
        self._codegen_input = codegen_input
        self._entry_point = entry_point
        self._converter = converter
        self._module_plan = module_plan
        self._trace_operations = trace_operations
        self._output_dir = output_dir
        self._entry_definition: action_context.ActionDefinitionContext

    def generate(
        self,
        *,
        max_workers: int | None,
    ) -> tuple[action_context.ActionDefinitionContext, set[Path]]:
        """Generate every definition with bounded worker concurrency."""
        package_dirs: set[Path] = set()
        for package_dir in reference_graph_executor.process_definitions(
            self._codegen_input.definition_order,
            self._generate_definition,
            max_workers=max_workers,
        ):
            if package_dir is not None:
                package_dirs.add(package_dir)
        return self._entry_definition, package_dirs

    def _generate_definition(self, definition: ast.GlobalDefinition) -> Path | None:
        if not _generates_module_part(definition):
            return None
        definition_index = self._module_plan.definition_indexes[
            definition.typed_name.full_typed_name
        ]
        if isinstance(definition, ast.ActionDefinition):
            action = self._generate_action(definition)
            module_name = action.module_name
            part = _ModulePart(
                definition_index=definition_index,
                body=_templates.render_action(action),
                imports=action.imports,
                typing_names=_typing_names(
                    classvar=action.needs_classvar,
                    never=action.needs_never,
                    override=True,
                ),
                needs_runtime_import=True,
            )
        elif isinstance(definition, ast.EncodingOperationDefinition):
            encoding_operation = (
                encoding_operation_definition.EncodingOperationDefinitionGenerator(
                    self._codegen_input.encoding_operations[
                        definition.typed_name.full_typed_name
                    ],
                    self._converter,
                ).generate()
            )
            module_name = encoding_operation.module_name
            part = _ModulePart(
                definition_index=definition_index,
                body=_templates.render_encoding_operation(encoding_operation),
                imports=encoding_operation.imports,
                typing_names=[],
                needs_runtime_import=False,
            )
        else:
            position = position_definition.PositionDefinitionGenerator(
                typing.cast("ast.PositionDefinition", definition),
                self._converter,
            ).generate()
            module_name = position.module_name
            part = _ModulePart(
                definition_index=definition_index,
                body=_templates.render_position(position),
                imports=position.imports,
                typing_names=_typing_names(
                    classvar=position.needs_classvar,
                    never=position.needs_never,
                    override=False,
                ),
                needs_runtime_import=True,
            )
        shared_module = self._module_plan.shared_modules.get(module_name)
        if shared_module is None:
            return self._write_module(module_name, [part])
        parts = shared_module.add_part(part)
        if parts is None:
            return None
        return self._write_module(module_name, parts)

    def _generate_action(
        self,
        definition: ast.ActionDefinition,
    ) -> action_context.ActionDefinitionContext:
        context = action_definition.ActionDefinitionGenerator(
            self._codegen_input.actions[definition.typed_name.full_typed_name],
            self._converter,
            trace_operations=self._trace_operations,
        ).generate()
        if definition.typed_name == self._entry_point.typed_name:
            self._entry_definition = context
        return context

    def _write_module(self, module_name: str, parts: list[_ModulePart]) -> Path:
        """Write a module containing the given definitions' classes."""
        imports: set[str] = set()
        typing_names: set[str] = set()
        for part in parts:
            imports.update(part.imports)
            typing_names.update(part.typing_names)
        content = _templates.render_module_header(
            sorted(imports),
            sorted(typing_names),
            any(part.needs_runtime_import for part in parts),
        )
        for part in parts:
            content += "\n\n" + part.body
        relative_file_path = naming.file_path_for_module(module_name)
        file_path = self._output_dir / relative_file_path
        file_path.parent.mkdir(parents=True, exist_ok=True)
        _ = file_path.write_text(content)
        return relative_file_path.parent.parent


class PythonLiteralCodeGenerator:
    """Generates literal Python code for a validated Define entry point."""

    def generate(
        self,
        codegen_input: codegen_input_types.CodegenInput,
        entry_point: ast.ActionDefinition,
        output_dir: Path,
        *,
        trace_operations: bool = False,
        max_workers: int | None = None,
    ):
        """Generate Python files for the entry-point constructor and its references."""
        converter = naming.NameConverter()
        module_plan = _ModulePlan.from_definitions(
            codegen_input.definition_order.definitions, converter
        )
        entry_definition, package_dirs = _DefinitionGenerator(
            codegen_input,
            entry_point,
            converter,
            module_plan,
            output_dir,
            trace_operations=trace_operations,
        ).generate(max_workers=max_workers)

        self._write_init_files(package_dirs, output_dir)
        self._write_entry_point(entry_definition, output_dir)

    @staticmethod
    def _write_init_files(package_dirs: set[Path], output_dir: Path):
        """Write empty __init__.py files for intermediate packages."""
        needed_dirs: set[Path] = set()
        for package_dir in package_dirs:
            needed_dirs.add(package_dir)
            for parent in package_dir.parents:
                if parent == Path():
                    continue
                needed_dirs.add(parent)

        for dir_path in sorted(needed_dirs):
            init_file = output_dir / dir_path / "__init__.py"
            if not init_file.exists():
                _ = init_file.write_text(_PACKAGE_INIT)

    @staticmethod
    def _write_entry_point(
        context: action_context.ActionDefinitionContext,
        output_dir: Path,
    ):
        """Write the __main__.py entry point file."""
        content = _templates.render_entry_point(
            entry_reference=naming.ClassReference(
                module_name=context.module_name,
                class_name=context.class_name,
            ),
            trace_operations=context.trace_operations,
        )
        _ = (output_dir / "__main__.py").write_text(content)
