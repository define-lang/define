"""Generate define/compiler/parsing/invisible_characters_data.py from the Unicode Character Database."""

from __future__ import annotations

import typing
import urllib.request
from pathlib import Path
from typing import cast

if typing.TYPE_CHECKING:
    import http.client

UNICODE_VERSION = "18.0.0"
UNICODE_DATA_URL = "https://www.unicode.org/Public/18.0.0/ucd/UnicodeData.txt"
DERIVED_CORE_PROPERTIES_URL = (
    "https://www.unicode.org/Public/18.0.0/ucd/DerivedCoreProperties.txt"
)
OUTPUT_PATH = (
    Path(__file__).resolve().parent.parent
    / "define"
    / "compiler"
    / "parsing"
    / "invisible_characters_data.py"
)

# General categories whose characters never display.
_INVISIBLE_CATEGORIES = frozenset({"Cc", "Cf", "Cs", "Co", "Cn", "Zs", "Zl", "Zp"})
# The Invisible Characters rule allows these only in some contexts, so the
# parser checks them in context instead of listing them as invisible.
_CONTEXTUAL_CHARACTERS = frozenset(
    {0x061C, 0x200C, 0x200D, 0x200E, 0x200F, 0xFE0E, 0xFE0F}
)
_MAX_CODE_POINT = 0x10FFFF


def _download_unicode_data() -> str:
    with cast(
        "http.client.HTTPResponse",
        urllib.request.urlopen(UNICODE_DATA_URL, timeout=30),
    ) as response:
        return response.read().decode("utf-8")


def _download_derived_core_properties() -> str:
    with cast(
        "http.client.HTTPResponse",
        urllib.request.urlopen(DERIVED_CORE_PROPERTIES_URL, timeout=30),
    ) as response:
        return response.read().decode("utf-8")


def general_categories(unicode_data: str) -> dict[int, str]:
    """Return the general category of every assigned code point in UnicodeData.txt."""
    categories: dict[int, str] = {}
    range_start: int | None = None
    for line in unicode_data.splitlines():
        fields = line.split(";")
        code_point = int(fields[0], 16)
        name = fields[1]
        category = fields[2]
        # Large blocks are listed as a First/Last pair instead of one line each.
        if name.endswith(", First>"):
            range_start = code_point
            continue
        if name.endswith(", Last>") and range_start is not None:
            for ranged_code_point in range(range_start, code_point + 1):
                categories[ranged_code_point] = category
            range_start = None
            continue
        categories[code_point] = category
    return categories


def default_ignorable_code_points(derived_core_properties: str) -> set[int]:
    """Return the code points with the Default_Ignorable_Code_Point property."""
    code_points: set[int] = set()
    for line in derived_core_properties.splitlines():
        data = line.split("#", 1)[0].strip()
        if not data:
            continue
        fields = [field.strip() for field in data.split(";")]
        if fields[1] != "Default_Ignorable_Code_Point":
            continue
        code_point_range = fields[0]
        start, _, end = code_point_range.partition("..")
        code_points.update(range(int(start, 16), int(end or start, 16) + 1))
    return code_points


def invisible_ranges(
    categories: dict[int, str], default_ignorable: set[int]
) -> list[tuple[int, int]]:
    """Return the inclusive ranges of invisible non-ASCII code points."""
    ranges: list[tuple[int, int]] = []
    for code_point in range(0x80, _MAX_CODE_POINT + 1):
        if code_point in _CONTEXTUAL_CHARACTERS:
            continue
        category = categories.get(code_point, "Cn")
        if (
            category not in _INVISIBLE_CATEGORIES
            and code_point not in default_ignorable
        ):
            continue
        if ranges and ranges[-1][1] == code_point - 1:
            ranges[-1] = (ranges[-1][0], code_point)
        else:
            ranges.append((code_point, code_point))
    return ranges


def render(ranges: list[tuple[int, int]]) -> str:
    """Render the generated module."""
    lines = [
        '"""Invisible non-ASCII characters for the Invisible Characters rule.',
        "",
        f"Generated by tools/generate_invisible_characters.py from Unicode {UNICODE_VERSION}.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        f'UNICODE_VERSION = "{UNICODE_VERSION}"',
        "",
        "# Inclusive ranges of invisible code points, other than the characters",
        "# that the rule allows in some contexts.",
        "INVISIBLE_RANGES: tuple[tuple[int, int], ...] = (",
    ]
    lines.extend(f"    (0x{start:04X}, 0x{end:04X})," for start, end in ranges)
    lines.append(")")
    return "\n".join(lines) + "\n"


def main():
    """Download the Unicode Character Database files and write the generated module."""
    ranges = invisible_ranges(
        general_categories(_download_unicode_data()),
        default_ignorable_code_points(_download_derived_core_properties()),
    )
    _ = OUTPUT_PATH.write_text(render(ranges))


if __name__ == "__main__":
    main()
