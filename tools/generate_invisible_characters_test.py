from __future__ import annotations

from tools import generate_invisible_characters, runfiles


def test_generated_data_matches_generator_unicode_version():
    rust_data = runfiles.resolve_from_env("INVISIBLE_RANGES").read_text(
        encoding="utf-8"
    )
    assert f"//! Unicode {generate_invisible_characters.UNICODE_VERSION}." in rust_data


def test_render_rust_groups_long_hex_literals():
    assert generate_invisible_characters.render_rust(
        [(0x80, 0x9F), (0x3FC40, 0x10FFFF)]
    ) == (
        "//! Invisible non-ASCII characters for the Invisible Characters rule, from\n"
        + f"//! Unicode {generate_invisible_characters.UNICODE_VERSION}.\n"
        + "//!\n"
        + "//! Generated by `tools/generate_invisible_characters.py`.\n"
        + "\n"
        + "/// Inclusive ranges of invisible code points, in order, other than the\n"
        + "/// characters that the rule allows in some contexts.\n"
        + "pub const INVISIBLE_RANGES: [(u32, u32); 2] = [\n"
        + "    (0x0080, 0x009F),\n"
        + "    (0x3FC40, 0x10_FFFF),\n"
        + "];\n"
    )
